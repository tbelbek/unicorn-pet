#!/usr/bin/env python3
"""fw/src/portal.html -> fw/src/portal.gen.h (a C string in flash). Run after editing the page;
`make -C test portal` checks that the header is up to date."""
import pathlib, sys

root = pathlib.Path(__file__).resolve().parent.parent
html = (root / "fw/src/portal.html").read_bytes()
# one token per byte; octal escapes (at most 3 digits) never swallow the next character
tokens = ["\\%03o" % b if b >= 0x80 or b < 0x20 or b in (0x22, 0x5c) or b == 0x3f else chr(b) for b in html]
lines, cur = [], ""
for t in tokens:
    cur += t
    if len(cur) >= 100:
        lines.append(cur); cur = ""
if cur: lines.append(cur)
text = ("// Generated by tools/embed_portal.py from portal.html: do not edit.\n#pragma once\n"
        "static const char PORTAL_HTML[] =\n" + "\n".join(f'    "{l}"' for l in lines) + ";\n")
dst = root / "fw/src/portal.gen.h"
if len(sys.argv) > 1 and sys.argv[1] == "--check":
    sys.exit(0 if dst.exists() and dst.read_text() == text else "fw/src/portal.gen.h is stale: run tools/embed_portal.py")
dst.write_text(text)
print(f"wrote {dst.relative_to(root)} ({len(html)} bytes)")

#!/usr/bin/env python3
"""tools/i18n.py -> core/strings.gen.h: one table of every string, per language.
`--check` fails if the header is stale (make -C test i18n)."""
import pathlib, sys
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from i18n import LANGS, NATIVE, S

root = pathlib.Path(__file__).resolve().parent.parent


def c_str(s):
    out = []
    for b in s.encode("utf-8"):
        out.append("\\%03o" % b if b >= 0x80 or b < 0x20 or b in (0x22, 0x5c, 0x3f) else chr(b))
    return '"' + "".join(out) + '"'


def text(key, lang):
    v = S[key]
    return v.get(lang) or v["en"]


keys = list(S)
lines = ["// Generated by tools/export_i18n.py from tools/i18n.py: do not edit.", "#pragma once", "",
         "enum Str {"]
lines += [f"    S_{k}," for k in keys] + ["    S_COUNT", "};", ""]
lines.append(f"enum {{ STR_LANGS = {len(LANGS)} }};")
lines.append("static const char* const UP_LANG_NAME[STR_LANGS] = {")
lines.append("    " + ", ".join(c_str(NATIVE[l]) for l in LANGS) + ",")
lines.append("};")
lines.append("static const char* const UP_STR[STR_LANGS][S_COUNT] = {")
for lang in LANGS:
    lines.append(f"    {{   // {lang}")
    lines += [f"        {c_str(text(k, lang))}," for k in keys]
    lines.append("    },")
lines.append("};")
out = "\n".join(lines) + "\n"

dst = root / "core/strings.gen.h"
if len(sys.argv) > 1 and sys.argv[1] == "--check":
    missing = [(k, l) for k in keys for l in LANGS if l not in S[k]]
    if missing:
        sys.exit(f"untranslated: {missing[:8]}{' ...' if len(missing) > 8 else ''}")
    sys.exit(0 if dst.exists() and dst.read_text() == out else "core/strings.gen.h is stale: run tools/export_i18n.py")
dst.write_text(out)
print(f"wrote {dst.relative_to(root)}: {len(keys)} strings x {len(LANGS)} languages")

